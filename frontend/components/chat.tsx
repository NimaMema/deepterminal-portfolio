"use client";

import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { Bot, Send, User } from "lucide-react";
import { useEffect, useRef, useState } from "react";
import { api, post } from "@/lib/api";
import { useDemo } from "@/lib/demo";
import { date } from "@/lib/format";
import type { Evidence } from "@/lib/types";
import { CitedText } from "./evidence";
import { Button, Notice, Unavailable } from "./ui";

interface Msg { id: number; role: string; content: string; generated_by: string | null; citations: Evidence[]; created_at: string; usage: Record<string, unknown> }
interface Session { id: string; company_id: number | null; title: string; messages: Msg[] }

const SUGGEST = ["What are the main supply-chain risks?", "How has revenue growth compared with management's outlook?",
  "Are there any accounting red flags?", "What does the current price imply about growth?", "Who are the key suppliers and where are they?"];

export function Chat({ companyId, initialSession, initialText }: { companyId: number | null; initialSession?: string | null; initialText?: string | null }) {
  const qc = useQueryClient();
  const isDemo = useDemo();
  const [sid, setSid] = useState<string | null>(initialSession ?? null);
  const [text, setText] = useState(initialText ?? "");
  const endRef = useRef<HTMLDivElement>(null);
  const sessions = useQuery({ queryKey: ["sessions", companyId], enabled: !!companyId,
    queryFn: () => api<{ id: string; title: string; created_at: string }[]>(`/chat/sessions?company_id=${companyId}`) });
  const first = useRef(true);
  useEffect(() => { if (first.current) { first.current = false; return; } setSid(null); }, [companyId]);
  // A question passed in starts a new conversation rather than opening the latest one.
  const fresh = useRef(!!initialText);
  useEffect(() => { if (!sid && !fresh.current && sessions.data?.length) setSid(sessions.data[0].id); }, [sessions.data, sid]);
  const session = useQuery({ queryKey: ["session", sid], enabled: !!sid, queryFn: () => api<Session>(`/chat/sessions/${sid}`) });
  const send = useMutation({
    mutationFn: async (q: string) => {
      let s = sid;
      if (!s) { const n = await post<{ id: string }>("/chat/sessions", { company_id: companyId, title: q.slice(0, 60) }); s = n.id; setSid(s); }
      return post<Msg>(`/chat/sessions/${s}/messages`, { content: q });
    },
    onSuccess: () => { setText(""); qc.invalidateQueries({ queryKey: ["session"] }); qc.invalidateQueries({ queryKey: ["sessions", companyId] }); },
  });
  useEffect(() => { endRef.current?.scrollIntoView({ behavior: "smooth" }); }, [session.data?.messages.length, send.isPending]);
  if (!companyId) return <Notice>Choose a company to chat about its evidence.</Notice>;
  return (
    <div className="flex h-[calc(100dvh-220px)] min-h-[480px] flex-col rounded-xl border border-ink-700 bg-ink-900">
      <div className="flex items-center gap-2 border-b border-ink-700 px-4 py-2 text-xs">
        <span className="text-fg-3">Conversation</span>
        <select aria-label="Conversation" value={sid ?? ""} onChange={(e) => setSid(e.target.value || null)} className="rounded border border-ink-600 bg-ink-850 px-2 py-1 text-xs">
          <option value="">New conversation</option>{sessions.data?.map((s) => <option key={s.id} value={s.id}>{s.title}</option>)}</select>
      </div>
      <div className="scroll-thin flex-1 space-y-4 overflow-y-auto p-4" aria-live="polite">
        {!session.data?.messages.length && !send.isPending && (
          <div className="mx-auto max-w-xl pt-8 text-center">
            <Bot className="mx-auto text-accent" aria-hidden /><p className="mt-2 text-sm text-fg-2">Ask about this company. Answers cite evidence you can open; nothing is stated without a source.</p>
            <div className="mt-4 flex flex-wrap justify-center gap-2">{SUGGEST.map((s) => <button key={s} onClick={() => send.mutate(s)} className="rounded-full border border-ink-600 px-3 py-1 text-xs text-fg-2 hover:border-accent/60 hover:text-fg">{s}</button>)}</div>
          </div>
        )}
        {session.data?.messages.map((m) => (
          <div key={m.id} className={`flex gap-3 ${m.role === "user" ? "justify-end" : ""}`}>
            {m.role !== "user" && <div className="mt-1 grid size-7 shrink-0 place-items-center rounded-full bg-accent/15 text-accent"><Bot size={15} aria-hidden /></div>}
            <div className={`max-w-[85%] rounded-xl px-4 py-3 text-sm leading-relaxed ${m.role === "user" ? "bg-accent/15 text-fg" : "border border-ink-700 bg-ink-850 text-fg-2"}`}>
              <div className="whitespace-pre-line"><CitedText text={m.content} /></div>
              {m.role !== "user" && <div className="mt-2 text-[11px] text-fg-3">{m.generated_by === "rules" ? (isDemo ? "Extractive answer (rule-based; the public demo runs no LLM)" : "Extractive answer (no LLM configured)") : `Generated by ${m.generated_by}`}{isDemo && m.generated_by !== "rules" ? ` · recorded ${date(m.created_at)} on a 4-core CPU, no GPU; precomputed for the demo` : ""} · {m.citations.length} cited source(s)</div>}
            </div>
            {m.role === "user" && <div className="mt-1 grid size-7 shrink-0 place-items-center rounded-full bg-ink-700"><User size={15} aria-hidden /></div>}
          </div>
        ))}
        {send.isPending && <div className="flex gap-3"><div className="skeleton h-16 w-2/3" /></div>}
        {send.error && <Unavailable error={send.error} compact />}
        <div ref={endRef} />
      </div>
      <form className="flex gap-2 border-t border-ink-700 p-3" onSubmit={(e) => { e.preventDefault(); if (text.trim()) send.mutate(text.trim()); }}>
        <textarea value={text} onChange={(e) => setText(e.target.value)} rows={1} aria-label="Ask a question"
          onKeyDown={(e) => { if (e.key === "Enter" && !e.shiftKey) { e.preventDefault(); if (text.trim()) send.mutate(text.trim()); } }}
          placeholder="Ask about filings, risks, financials, valuation…" className="flex-1 resize-none rounded-md border border-ink-600 bg-ink-850 px-3 py-2 text-sm text-fg placeholder:text-fg-3 focus:border-accent focus:outline-none" />
        <Button type="submit" variant="primary" loading={send.isPending} aria-label="Send"><Send size={14} /></Button>
      </form>
    </div>
  );
}
